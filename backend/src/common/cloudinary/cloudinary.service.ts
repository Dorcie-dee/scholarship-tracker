import { Injectable, Logger, OnModuleInit } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { v2 as cloudinary, UploadApiResponse } from 'cloudinary';
import { Readable } from 'stream';
import { AppConfig } from '../../config/configuration';

export interface UploadedFileResult {
  publicId: string;
  url: string;
  secureUrl: string;
  bytes: number;
  format: string;
  resourceType: string;
}

/**
 * Thin abstraction over the Cloudinary SDK. Nothing outside this service should
 * import `cloudinary` directly (spec §24) — that keeps a future storage-backend
 * swap to a single file.
 *
 * V1 scope: upload + delete only. Document metadata (type, version, ownership)
 * lives in the `documents` module's own entity, not here.
 */
@Injectable()
export class CloudinaryService implements OnModuleInit {
  private readonly logger = new Logger(CloudinaryService.name);
  private configured = false;

  constructor(private readonly configService: ConfigService<AppConfig, true>) {}

  onModuleInit(): void {
    const { cloudName, apiKey, apiSecret } = this.configService.get(
      'cloudinary',
      { infer: true },
    );

    if (!cloudName || !apiKey || !apiSecret) {
      this.logger.warn(
        'Cloudinary is not configured (CLOUDINARY_* env vars missing) — document uploads will fail until it is.',
      );
      return;
    }

    cloudinary.config({
      cloud_name: cloudName,
      api_key: apiKey,
      api_secret: apiSecret,
      secure: true,
    });
    this.configured = true;
  }

  isConfigured(): boolean {
    return this.configured;
  }

  /**
   * Uploads a buffer (e.g. from a Multer memory-storage file) to Cloudinary under
   * a folder scoped to the owning user, so files are trivially attributable and
   * listable per-user in the Cloudinary console.
   *
   * Production hardening (Batch 6) — `type: 'authenticated'`: the asset is
   * NOT retrievable via its plain URL at all — every access requires a
   * signature Cloudinary itself verifies (see `getSignedDeliveryUrl()`
   * below). Previously `type: 'upload'` (the default) — a permanently
   * public, unauthenticated URL — was genuinely unacceptable for what this
   * app's own `DocumentType` enum identifies as identity-adjacent personal
   * documents (passport copies, transcripts). See docs/decisions.md,
   * "Document delivery: authenticated, signed URLs".
   */
  async uploadBuffer(
    buffer: Buffer,
    options: { folder: string; filename?: string },
  ): Promise<UploadedFileResult> {
    if (!this.configured) {
      throw new Error(
        'Cloudinary is not configured. Set CLOUDINARY_CLOUD_NAME/API_KEY/API_SECRET.',
      );
    }

    const result = await new Promise<UploadApiResponse>((resolve, reject) => {
      const uploadStream = cloudinary.uploader.upload_stream(
        {
          folder: options.folder,
          resource_type: 'auto',
          type: 'authenticated',
          filename_override: options.filename,
          use_filename: Boolean(options.filename),
          unique_filename: true,
        },
        (error, result) => {
          if (error || !result) {
            reject(
              new Error(
                error?.message ?? 'Cloudinary upload returned no result',
              ),
            );
            return;
          }
          resolve(result);
        },
      );
      Readable.from(buffer).pipe(uploadStream);
    });

    return {
      publicId: result.public_id,
      url: result.url,
      secureUrl: result.secure_url,
      bytes: result.bytes,
      format: result.format,
      resourceType: result.resource_type,
    };
  }

  /**
   * Production hardening (Batch 6) — a signed delivery URL for an
   * `authenticated`-type asset. The signature (HMAC, using the account's own
   * API secret — already configured, no additional Cloudinary feature
   * needed) proves the URL was generated by this backend, not guessed or
   * constructed from a leaked `publicId` alone; a caller can never request
   * one for a document they don't own — see
   * `DocumentsService.getSignedDownloadUrl()`, the only caller, which runs
   * the same ownership check as every other Document read.
   *
   * **Honest scope — this is signed, not time-expiring.** True
   * server-enforced expiry (a URL Cloudinary itself refuses after N
   * seconds) requires Cloudinary's token-based-authentication add-on
   * (`auth_token`), a separate opt-in account feature with its own secret
   * key this codebase has no way to detect or configure — attempting to use
   * it without that key configured throws (confirmed directly: `cloudinary.
   * url(..., { auth_token: {...} })` crashes with a digest error when no
   * `auth_token.key` is set — verified in this checkpoint, not assumed).
   * Shipping that unconditionally would trade a working feature for a
   * broken one on any account without the add-on enabled. `ttlSeconds` is
   * accepted and returned to the caller as the *intended* validity window
   * (communicated to the client) but is not currently enforced by
   * Cloudinary itself — see docs/decisions.md, "Document delivery: signed
   * URLs, not yet time-expiring" for the full reasoning and the concrete
   * follow-up (wire up `auth_token` once a Cloudinary account with that
   * add-on is available to actually test against).
   */
  getSignedDeliveryUrl(
    publicId: string,
    resourceType: 'image' | 'raw' | 'video',
  ): string {
    if (!this.configured) {
      throw new Error(
        'Cloudinary is not configured. Set CLOUDINARY_CLOUD_NAME/API_KEY/API_SECRET.',
      );
    }
    return cloudinary.url(publicId, {
      type: 'authenticated',
      resource_type: resourceType,
      sign_url: true,
      secure: true,
    });
  }

  async deleteByPublicId(
    publicId: string,
    resourceType: 'image' | 'raw' | 'video' = 'image',
  ): Promise<void> {
    if (!this.configured) {
      return;
    }
    await cloudinary.uploader.destroy(publicId, {
      resource_type: resourceType,
      type: 'authenticated',
    });
  }
}
