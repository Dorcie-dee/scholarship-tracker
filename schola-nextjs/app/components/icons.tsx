import type { SVGProps } from 'react';

export interface IconProps extends SVGProps<SVGSVGElement> {
  size?: number;
}

/**
 * One consistent stroke-icon set for the whole app (1.75 stroke, round caps)
 * instead of an icon-font dependency — keeps the bundle small and every icon
 * visually related. Decorative icons should get `aria-hidden="true"` from
 * the call site; an icon that IS the only label on a control needs
 * `aria-label` on that control instead.
 */
function Base({ size = 20, children, ...props }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      {...props}
    >
      {children}
    </svg>
  );
}

